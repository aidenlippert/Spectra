"""Conventional adaptive sparse Taylor with directly constructed residual proof.

P_m=sum G^k O t^k/k! has R_m=-G c_m t^m. A proposer can use this
algebra to avoid recomputing lower zero coefficients; the independent checker
still recomputes and verifies them. This is supplied baseline mathematics.
"""
from fractions import Fraction as F
from time import perf_counter
from .v7_certificate import Piece, norm_witness, check_certificate


def adaptive_taylor(gen, initial, duration, tolerance, max_order=24):
 if not 0 <= max_order <= 24: raise ValueError('order cap')
 if duration <= 0 or tolerance < 0: raise ValueError('duration/tolerance')
 coeffs=[dict(initial)]; probes=[]; sorting=0;pairs=0
 for m in range(max_order+1):
  derivative=gen.apply(coeffs[-1])
  factor=duration**(m+1)/F(m+1)
  for grouping in ('l1','firstfit','weighted'):
   groups,cost=norm_witness(derivative,grouping)
   sorting+=cost['sorted_terms'];pairs+=cost['group_comparisons']
   bound=factor*sum((F(g['upper']) for g in groups),F(0))
   probes.append(dict(order=m,grouping=grouping,bound=str(bound)))
   if bound<=tolerance:
    # Exact polynomial generated by recurrence; verifier must confirm zeros.
    ws={'jump:0':[]}
    ws.update({f'residual:0:{j}':[] for j in range(m+1)})
    if derivative:
     ws[f'residual:0:{m}']=groups
    else:
     # Checker trims identically zero high residual coefficients to degree 0.
     ws={'jump:0':[],'residual:0:0':[]}
    witness=dict(schema='v7-residual-1',integration_basis='power',witnesses=ws,
                 claimed_bound=str(bound),construction_cost=dict(group_comparisons=pairs,sorted_terms=sorting))
    return Piece(duration,tuple(coeffs)),witness,dict(probes=probes,generator=dict(gen.cost),peak_polynomial_entries=sum(map(len,coeffs)))
  if m<max_order:coeffs.append({p:c/F(m+1) for p,c in derivative.items()})
 raise ValueError('Taylor order budget without certificate')
