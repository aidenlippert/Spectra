"""Bounded experiment for compressing PSD SOS Gram certificates.

This is a numerical proposal study.  It does not rewrite a certificate or
claim that a truncated Gram remains a valid lower-bound proof.  The relevant
error is the coefficient residual after the Gram is mapped through an
operator dictionary.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from fractions import Fraction
import sys
import copy
import time

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from experiments.marginal_coefficient import coefficient_rows, gram_map, dagger
from experiments.marginal_symbolic import word_product
from experiments.marginal_symbolic import verify

import numpy as np


def instance(size: int, seed: int) -> tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(seed)
    q, _ = np.linalg.qr(rng.normal(size=(size, size)))
    # Algebraic tail, with a small isotropic floor so rank is not free.
    eig = 1.0 / (1.0 + np.arange(size, dtype=float)) ** 1.35
    gram = (q * eig) @ q.T
    # A fixed linear dictionary map: each Gram entry contributes to an
    # independently normalized coefficient direction.  This is a conservative
    # proxy for coefficient residual; real CAR dictionaries need their map.
    dictionary = rng.normal(size=(size, size, size))
    dictionary /= np.linalg.norm(dictionary.reshape(size * size, size), axis=0)
    return gram, dictionary


def map_residual(delta: np.ndarray, dictionary: np.ndarray) -> float:
    coeff = np.einsum("ij,ijk->k", delta, dictionary, optimize=True)
    return float(np.linalg.norm(coeff))


def exact_coefficients(words, matrix, lookup):
    """Map a rational Gram through CAR multiplication exactly."""
    # Keep every CAR word generated by the block.  Restricting to the
    # Hamiltonian's degree-4 rows would silently hide higher-body residuals.
    out = {}
    for i, left in enumerate(words):
        for j, right in enumerate(words):
            value = matrix[i][j]
            if not value:
                continue
            for word, sign in word_product(dagger(tuple(tuple(x) for x in left)), tuple(tuple(x) for x in right)):
                out[word] = out.get(word, Fraction(0)) + value * sign
    return out


def quantized_spectral_factor(gram, rank, denominator=10**8):
    values, vectors = np.linalg.eigh(gram)
    keep = np.argsort(values)[-rank:]
    factor = vectors[:, keep] * np.sqrt(np.maximum(values[keep], 0.0))
    integers = np.rint(factor * denominator).astype(np.int64)
    return integers, denominator


def spectral(gram: np.ndarray, rank: int) -> np.ndarray:
    values, vectors = np.linalg.eigh(gram)
    keep = np.argsort(values)[-rank:]
    return (vectors[:, keep] * values[keep]) @ vectors[:, keep].T


def entrywise(gram: np.ndarray, count: int) -> np.ndarray:
    out = np.zeros_like(gram)
    tri = np.triu_indices_from(gram)
    order = np.argsort(np.abs(gram[tri]))[::-1][:count]
    ii, jj = tri[0][order], tri[1][order]
    out[ii, jj] = gram[ii, jj]
    out[jj, ii] = gram[ii, jj]
    return out


def actual_instance(path: Path, backend: str = "numpy") -> tuple[list[dict], int]:
    xp = np
    if backend == "cupy":
        import cupy as cp
        xp = cp
    data = json.loads(path.read_text())
    denominator = Fraction(data["denominator"])
    blocks = []
    for block in data["blocks"]:
        factor_int = block["factor"]
        factor = xp.asarray(factor_int, dtype=float) / float(denominator)
        gram = factor.T @ factor
        gram = xp.asnumpy(gram) if backend == "cupy" else gram
        blocks.append({"name": block["name"], "words": block["words"], "gram": gram,
                       "factor_int": factor_int, "denominator": denominator,
                       "factor_shape": list(factor.shape)})
    return blocks, int(data["modes"])


def campaign(fixture: Path, outputdir: Path, caps=(1, 2, 4, 8, 16, 32, 64, "full"), backend="numpy"):
    """Write and exactly verify full-certificate rank-cap proposals."""
    source = json.loads(fixture.read_text())
    outputdir.mkdir(parents=True, exist_ok=True)
    blocks, _ = actual_instance(fixture, backend)
    decompositions = []
    eig_started = time.monotonic()
    for item in blocks:
        gram = item["gram"]
        if backend == "cupy":
            import cupy as cp
            values, vectors = cp.linalg.eigh(cp.asarray(gram))
            values, vectors = cp.asnumpy(values), cp.asnumpy(vectors)
        else:
            values, vectors = np.linalg.eigh(gram)
        decompositions.append((values, vectors, item["factor_int"], item["denominator"]))
    eig_seconds = time.monotonic() - eig_started
    receipts = []
    for cap in caps:
        started = time.monotonic()
        candidate = copy.deepcopy(source)
        candidate["blocks"] = []
        for source_block, (values, vectors, original, denominator) in zip(source["blocks"], decompositions):
            if cap == "full":
                factor = original
            else:
                rank = min(int(cap), len(values))
                keep = np.argsort(values)[-rank:]
                # Verifier stores factor rows L with Q=L.T@L.
                raw = (vectors[:, keep] * np.sqrt(np.maximum(values[keep], 0.0))).T
                factor = [[int(value) for value in row]
                          for row in np.rint(raw * float(denominator)).astype(np.int64).tolist()]
                factor = [row for row in factor if any(row)]
            candidate["blocks"].append({"name": source_block["name"], "words": source_block["words"], "factor": factor})
        name = f"rank_{cap}.json"
        target = outputdir / name
        target.write_text(json.dumps(candidate, separators=(",", ":")) + "\n")
        try:
            receipt = verify(candidate)
            status = "accepted"
        except Exception as exc:  # candidate remains a useful negative result
            receipt = {"error": f"{type(exc).__name__}: {exc}"}
            status = "rejected"
        receipt.update({"rank_cap": cap, "status": status, "certificate": name,
                        "bytes": target.stat().st_size, "elapsed_seconds": time.monotonic() - started,
                        "eigendecomposition_seconds": eig_seconds,
                        "backend": backend})
        receipts.append(receipt)
    (outputdir / "campaign_receipts.json").write_text(json.dumps(receipts, indent=2) + "\n")
    return receipts


def run(size: int = 32, seed: int = 7, fixture: Path | None = None,
        backend: str = "numpy") -> dict:
    if fixture:
        blocks, modes = actual_instance(fixture, backend)
        lookup = {w: i for i, w in enumerate(coefficient_rows(modes))}
        rows = []
        for block in blocks:
            gram = block["gram"]
            if backend == "cupy":
                import cupy as cp
                values, vectors = cp.linalg.eigh(cp.asarray(gram))
                values, vectors = cp.asnumpy(values), cp.asnumpy(vectors)
            else:
                values, vectors = np.linalg.eigh(gram)
            full = gram_map([tuple(tuple(x) for x in w) for w in block["words"]], lookup)
            original = np.asarray(full @ gram.reshape(-1, order="C")).ravel()
            words = [tuple(tuple(x) for x in w) for w in block["words"]]
            factor_exact = block["factor_int"]
            factor_den = block["denominator"]
            original_q = [[sum((Fraction(factor_exact[k][i]) * factor_exact[k][j] / factor_den**2
                                for k in range(len(factor_exact))), Fraction(0))
                           for j in range(len(words))] for i in range(len(words))]
            original_exact = exact_coefficients(words, original_q, lookup)
            for rank in sorted(set((1, 2, 4, min(8, len(values)), len(values)))):
                keep = np.argsort(values)[-rank:]
                approx = (vectors[:, keep] * values[keep]) @ vectors[:, keep].T
                residual = np.asarray(full @ (gram - approx).reshape(-1, order="C")).ravel()
                qint, qden = quantized_spectral_factor(gram, rank)
                qfactor = [[Fraction(int(qint[i, j]), qden) for j in range(qint.shape[1])] for i in range(qint.shape[0])]
                qgram = [[sum((qfactor[i][k] * qfactor[j][k] for k in range(qint.shape[1])), Fraction(0))
                          for j in range(len(words))] for i in range(len(words))]
                compressed_exact = exact_coefficients(words, qgram, lookup)
                exact_delta = {w: compressed_exact.get(w, Fraction(0)) - original_exact.get(w, Fraction(0))
                               for w in set(compressed_exact) | set(original_exact)}
                coefficient_l1 = sum(abs(v) for v in exact_delta.values())
                factor_entries = sum(v != 0 for row in qint.tolist() for v in row)
                rows.append({"block": block["name"], "method": "spectral", "budget": rank,
                             "dimension": len(values), "gram_rel_fro_error": float(np.linalg.norm(gram-approx)/max(np.linalg.norm(gram),1e-300)),
                             "operator_residual_l2": float(np.linalg.norm(residual)),
                             "operator_residual_linf": float(np.max(np.abs(residual))) if residual.size else 0.0,
                             "min_eigenvalue": float(np.linalg.eigvalsh(approx)[0]),
                             "quantization_denominator": qden,
                             "exact_coefficient_l1_residual": str(coefficient_l1),
                             "safe_scalar_penalty_l1": str(coefficient_l1),
                             "compressed_factor_nonzeros": factor_entries,
                             "baseline_factor_nonzeros": sum(v != 0 for row in block["factor_int"] for v in row)})
        return {"fixture": str(fixture), "modes": modes, "backend": backend,
                "blocks": len(blocks), "rows": rows,
                "exact_full_factor_replay": {"residual": "0",
                    "meaning": "same integer factor F and denominator d replayed against itself; no truncation"}}
    gram, dictionary = instance(size, seed)
    full_norm = float(np.linalg.norm(gram))
    rows = []
    for rank in (1, 2, 4, 8, 16, size):
        rank = min(rank, size)
        approx = spectral(gram, rank)
        rows.append({"method": "spectral", "budget": rank,
                     "gram_rank": int(np.linalg.matrix_rank(approx, tol=1e-12)),
                     "gram_rel_fro_error": float(np.linalg.norm(gram - approx) / full_norm),
                     "operator_residual": map_residual(gram - approx, dictionary),
                     "min_eigenvalue": float(np.linalg.eigvalsh(approx)[0])})
    for count in (size, 2 * size, 4 * size, 8 * size, size * (size + 1) // 2):
        count = min(count, size * (size + 1) // 2)
        approx = entrywise(gram, count)
        rows.append({"method": "entrywise", "budget": count,
                     "gram_rank": int(np.linalg.matrix_rank(approx, tol=1e-12)),
                     "gram_rel_fro_error": float(np.linalg.norm(gram - approx) / full_norm),
                     "operator_residual": map_residual(gram - approx, dictionary),
                     "min_eigenvalue": float(np.linalg.eigvalsh(approx)[0])})
    return {"size": size, "seed": seed, "spectrum": "(1+i)^-1.35",
            "dictionary": "deterministic random normalized linear map",
            "rows": rows}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--size", type=int, default=32)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--fixture", type=Path)
    parser.add_argument("--backend", choices=("numpy", "cupy"), default="numpy")
    parser.add_argument("--campaign", action="store_true")
    parser.add_argument("--outputdir", type=Path, default=Path("results/certificate_scaling/low_rank_compression/campaign"))
    args = parser.parse_args()
    if args.backend == "cupy":
        try:
            import cupy  # noqa: F401
        except ImportError as exc:
            raise SystemExit("--backend cupy requested but cupy is not installed") from exc
    if args.campaign:
        if not args.fixture:
            raise SystemExit("--campaign requires --fixture")
        result = campaign(args.fixture, args.outputdir, backend=args.backend)
        text = json.dumps(result, indent=2) + "\n"
        print(text, end="")
        return
    result = run(args.size, args.seed, args.fixture, args.backend)
    text = json.dumps(result, indent=2) + "\n"
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text)
    print(text, end="")


if __name__ == "__main__":
    main()
