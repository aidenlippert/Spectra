"""Bounded operator-dictionary scaling surrogate.

This experiment measures discovery of a low-energy subspace generated by a
priced operator dictionary.  It is deliberately separate from the SDP
certificate path: projected energies are numerical upper estimates and the
full diagonalization is only a reference.  The independent residual norm is
reported so that a small projected gap is not confused with a certificate.
"""
from __future__ import annotations

import argparse
import json
import itertools
import time
from pathlib import Path

import numpy as np


def basis(modes: int, particles: int) -> np.ndarray:
    return np.array([sum(1 << i for i in c) for c in itertools.combinations(range(modes), particles)], dtype=np.int64)


def hop(state: int, source: int, target: int):
    if not (state >> source) & 1 or (state >> target) & 1:
        return None
    sign = -1 if ((state & ((1 << source) - 1)).bit_count() & 1) else 1
    state ^= 1 << source
    sign *= -1 if ((state & ((1 << target) - 1)).bit_count() & 1) else 1
    return state ^ (1 << target), sign


def hubbard(modes: int, u: float = 4.0, t: float = 1.0, delta: float = 0.0):
    """Spinful open chain with an optional held-out bond perturbation."""
    if modes % 2 or modes < 4:
        raise ValueError("modes must be even and >=4")
    sites, n = modes // 2, modes // 2
    states = basis(modes, n); pos = {int(s): i for i, s in enumerate(states)}
    h = np.zeros((len(states), len(states)))
    for row, s in enumerate(states):
        for site in range(sites):
            up, dn = (s >> (2 * site)) & 1, (s >> (2 * site + 1)) & 1
            h[row, row] += u * up * dn
        for site in range(sites - 1):
            for spin in (0, 1):
                a, b = 2 * site + spin, 2 * (site + 1) + spin
                for src, dst, weight in ((a, b, -t), (b, a, -t),
                                         (a, b, -delta), (b, a, -delta)):
                    # delta is a second, held-out copy of the last bond.
                    if site != sites - 2 and weight in (-delta,):
                        continue
                    out = hop(int(s), src, dst)
                    if out is not None:
                        target, sign = out; h[pos[target], row] += weight * sign
    return states, h


def operator_columns(states: np.ndarray, max_distance: int = 2):
    """Return sparse-free excitation columns, each tagged by (src,dst)."""
    pos = {int(s): i for i, s in enumerate(states)}
    cols = []
    mode_count = int(states.max()).bit_length()
    for src in range(mode_count):
        for dst in range(mode_count):
            if src == dst or abs(src - dst) > 2 * max_distance + 1:
                continue
            v = np.zeros(len(states))
            for j, s in enumerate(states):
                out = hop(int(s), src, dst)
                if out is not None:
                    target, sign = out; v[pos[target]] = sign
            if np.linalg.norm(v) > 0:
                cols.append(((src, dst), v))
    return cols


def evaluate(h, columns, order, budget):
    q = np.zeros((len(h), 0)); rows = []
    for k in range(min(budget, len(order))):
        candidate = columns[order[k]][1][:, None]
        q, _ = np.linalg.qr(np.column_stack((q, candidate)))
        q = q[:, :k + 1]
        projected = q.T @ h @ q
        vals, vecs = np.linalg.eigh(projected)
        energy = float(vals[0]); psi = q @ vecs[:, 0]
        residual = float(np.linalg.norm(h @ psi - energy * psi))
        rows.append((energy, residual, int(np.count_nonzero(abs(psi) > 1e-12))))
    return rows


def adaptive_order(h, columns, budget):
    chosen, q = [], np.zeros((len(h), 0))
    for _ in range(min(budget, len(columns))):
        best = None
        for i, (_, v) in enumerate(columns):
            if i in chosen: continue
            z = v.copy()
            if q.shape[1]: z -= q @ (q.T @ z)
            if np.linalg.norm(z) < 1e-12: continue
            trial, _ = np.linalg.qr(np.column_stack((q, z[:, None])))
            trial = trial[:, :len(chosen) + 1]
            score = float(np.linalg.eigvalsh(trial.T @ h @ trial)[0])
            # Greedy Rayleigh pricing: each candidate is independently tested.
            key = (-score, -i)
            if best is None or key > best[0]: best = (key, i)
        chosen.append(best[1]); v = columns[best[1]][1][:, None]
        q, _ = np.linalg.qr(np.column_stack((q, v))); q = q[:, :len(chosen)]
    return chosen


def run(modes=(6, 8), budget=8, seed=90210):
    rng = np.random.default_rng(seed); receipt = {"scope": "numerical surrogate; no SDP certificate", "cases": []}
    for m in modes:
        states, h = hubbard(m); _, h_hold = hubbard(m, delta=0.27)
        exact, vec = np.linalg.eigh(h); exact_e = float(exact[0])
        columns = operator_columns(states)
        adaptive = adaptive_order(h, columns, budget)
        fixed = list(range(min(budget, len(columns))))
        random = list(rng.permutation(len(columns))[:budget])
        case = {"modes": m, "dimension": len(states), "dictionary": len(columns), "exact_reference": exact_e, "strategies": {}}
        for name, order in (("adaptive", adaptive), ("fixed", fixed), ("random", random)):
            started = time.perf_counter(); trace = evaluate(h, columns, order, budget)
            held = evaluate(h_hold, columns, order, budget)
            case["strategies"][name] = {"order": [columns[i][0] for i in order], "wall_seconds": time.perf_counter() - started,
                "trace": [{"energy": e, "residual_norm": r, "support": s, "error_to_full_reference": e - exact_e} for e, r, s in trace],
                "heldout_trace": [{"energy": e, "residual_norm": r, "support": s} for e, r, s in held]}
        receipt["cases"].append(case)
    out = Path(__file__).resolve().parents[2] / "results/certificate_scaling/operator_pricing"
    out.mkdir(parents=True, exist_ok=True); (out / "receipt.json").write_text(json.dumps(receipt, indent=2) + "\n")
    return receipt


if __name__ == "__main__":
    p = argparse.ArgumentParser(); p.add_argument("--modes", nargs="+", type=int, default=[6, 8]); p.add_argument("--budget", type=int, default=8); a = p.parse_args()
    print(json.dumps(run(tuple(a.modes), a.budget), indent=2))
